-- مخطط قاعدة بيانات موقع ناصر بوطيب.
-- نفّذ هذا الملف في Supabase SQL Editor عند إعداد مشروع جديد.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  summary text not null default '',
  body text not null,
  status text not null default 'draft' check (status in ('draft','published')),
  author_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  question_text text not null default '',
  author text not null default '',
  sources text not null default '',
  content_type text not null default 'article' check (content_type in ('fatwa','article','research','reply')),
  review_status text not null default 'pending' check (review_status in ('pending','reviewed'))
);

alter table public.articles add column if not exists question_text text not null default '';
alter table public.articles add column if not exists author text not null default '';
alter table public.articles add column if not exists sources text not null default '';
alter table public.articles add column if not exists content_type text not null default 'article';
alter table public.articles add column if not exists review_status text not null default 'pending';

-- تأكد من أن قيود نوع المحتوى تشمل الأنواع الحالية.
alter table public.articles drop constraint if exists articles_content_type_check;
alter table public.articles add constraint articles_content_type_check
  check (content_type in ('fatwa','article','research','reply'));
alter table public.articles drop constraint if exists articles_review_status_check;
alter table public.articles add constraint articles_review_status_check
  check (review_status in ('pending','reviewed'));

alter table public.admin_users enable row level security;
alter table public.articles enable row level security;

create or replace function public.is_site_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

-- صلاحيات SQL الأساسية، بالإضافة إلى سياسات RLS أدناه.
revoke all on public.admin_users from anon, authenticated;
grant select on public.admin_users to authenticated;
grant select on public.articles to anon, authenticated;
grant insert, update, delete on public.articles to authenticated;
grant usage, select on sequence public.articles_id_seq to authenticated;

-- حذف السياسات السابقة بالاسم نفسه يجعل إعادة تنفيذ الملف أسهل.
drop policy if exists "Admins can see admin membership" on public.admin_users;
drop policy if exists "Public reads published articles" on public.articles;
drop policy if exists "Admins insert articles" on public.articles;
drop policy if exists "Admins update articles" on public.articles;
drop policy if exists "Admins delete articles" on public.articles;

create policy "Admins can see admin membership" on public.admin_users
for select to authenticated using (public.is_site_admin());

-- الزوار يقرأون المنشور فقط؛ المدير يستطيع قراءة المسودات أيضًا.
create policy "Public reads published articles" on public.articles
for select to anon, authenticated using (status = 'published' or public.is_site_admin());
create policy "Admins insert articles" on public.articles
for insert to authenticated with check (public.is_site_admin());
create policy "Admins update articles" on public.articles
for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());
create policy "Admins delete articles" on public.articles
for delete to authenticated using (public.is_site_admin());

